import type { CodegenConfig } from "@graphql-codegen/cli";

// Keep in step with the API version the library is tested against
const ADMIN_API_VERSION = "2026-10";
// The scheduled workflow sets this to check against the next version
const apiVersion = process.env.SHOPIFY_API_VERSION ?? ADMIN_API_VERSION;

const config: CodegenConfig = {
  // Shopify's public Admin schema proxy, no access token needed
  schema: `https://shopify.dev/admin-graphql-direct-proxy/${apiVersion}`,
  // Queries are plucked from strings marked with /* graphql */
  documents: ["src/**/*.ts", "!src/generated/**", "!src/tests/**", "!src/examples/**"],
  generates: {
    "src/generated/admin.ts": {
      plugins: [
        { add: { content: `// Admin API ${apiVersion}. Generated by \`pnpm codegen\`, don't edit.` } },
        "typescript-operations",
      ],
      config: {
        enumsAsTypes: true,
        useTypeImports: true,
        avoidOptionals: { field: true, inputValue: false, object: true },
        scalars: {
          ID: "string",
          DateTime: "string",
          URL: "string",
          UnsignedInt64: "string",
        },
      },
    },
  },
};

export default config;
